const LANG_INDEX: Record<Lang, 0 | 1 | 2> = { hu: 0, en: 1, de: 2 };

function one(key: string, lang: Lang): string | null {
  const flat = key.toLowerCase().replace(/[^a-z0-9]/g, '');
  const hit = EXACT[flat] ?? EXACT[flat.replace(/^(is|has)/, '')];
  return hit ? hit[LANG_INDEX[lang]] : null;
}

// unknown keys are neptun's internal ui flags, nobody wants "Can panopto be opened"
export function fieldLabel(key: string, lang: Lang): string | null {
  const parts = key.split('.').map((k) => one(k, lang));
  return parts.every(Boolean) ? parts.join(' · ') : null;
}

// neptun's own translations, where they're just wrong
const VALUE_FIX: [RegExp, Tri][] = [[/^(edu[\s.-]*id\b.*|diákigazolvány)$/iu, ['Diákigazolvány', 'Student ID', 'Studierendenausweis']]];

export function fixValue(value: string, lang: Lang): string {
  const hit = VALUE_FIX.find(([re]) => re.test(value.trim()));
  return hit ? hit[1][LANG_INDEX[lang]] : value;
}